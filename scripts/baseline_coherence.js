/**
 * baseline_coherence.js — R22 Baseline Coherence Gate (P1.3b)
 *
 * Read-only by default. Verifies that knowledge/CURRENT_BASELINES.md (§1/§2/§4/§5)
 * and p2/CURRENT_BASELINES_P2.md (§1/§1b) agree with raw files:
 *   - §1/§5 SHA-256 hashes and sizes vs actual files
 *   - §2 per-pack Certified counts and grand total vs raw grep
 *   - §4 rule-table shape (19 rules) and test count vs live guard suite
 *   - P2 §1 per-pack QID/Certified/hash vs raw files
 *   - footer totals vs §2
 *
 *   --fix : refresh ONLY machine-derived tokens (hashes, sizes, counts,
 *           §4 rule table, footer totals). Prose corrections stay manual.
 *           Backs up each doc before writing. Refuses if raw counts are
 *           internally inconsistent (QID sum != per-state sum).
 *
 * Exit: 0 = coherent, 1 = divergences.
 */
