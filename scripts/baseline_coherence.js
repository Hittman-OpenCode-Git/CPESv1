let divergences = [];
function div(m) { divergences.push(m); console.log("  DIVERGE: " + m); }
function ok(m) { console.log("  OK: " + m); }

function sha(file) {
  const p = path.join(ROOT, file);
  if (!fs.existsSync(p)) return null;
  return crypto.createHash("sha256").update(fs.readFileSync(p)).digest("hex").toUpperCase();
}
function fsize(file) {
  const p = path.join(ROOT, file);
  if (!fs.existsSync(p)) return null;
  return fs.statSync(p).size;
}
function grepCount(file, re) {
  const p = path.join(ROOT, file);
  if (!fs.existsSync(p)) return null;
  const m = fs.readFileSync(p, "utf8").match(re);
  return m ? m.length : 0;
}
function packStats(file) {
  const q = grepCount(file, /"QuestionID"\s*:/g);
  const cert = grepCount(file, /"question_state"\s*:\s*"Certified"/g);
  const arch = grepCount(file, /"question_state"\s*:\s*"Archived"/g);
  const audit = grepCount(file, /"question_state"\s*:\s*"In Audit"/g);
  const unp = grepCount(file, /"question_state"\s*:\s*"Unprocessed"/g);
  const ed = grepCount(file, /"question_state"\s*:\s*"Editorial Queue"/g);
  return { q, cert, arch, audit, unp, ed };
}
function liveGuard() {
  try {
    const out = cp.execSync("node scripts/test_governance_guard.js", {
      cwd: ROOT, encoding: "utf8", timeout: 60000, maxBuffer: 10 * 1024 * 1024,
    });
    const m = out.match(/===\s*RESULTS:\s*(\d+)\s*PASS,\s*(\d+)\s*FAIL\s*===/);
    if (m) return { pass: +m[1], fail: +m[2] };
  } catch (e) { /* fall through */ }
  return null;
}
function escRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }
function rowLine(text, rowName) {
  const lines = text.split("\n");
  const idx = lines.findIndex(l => l.includes("`" + rowName + "`"));
  return idx === -1 ? null : { lines, idx, line: lines[idx] };
}
function firstHex(line) { const m = line.match(/[0-9A-Fa-f]{64}/); return m ? m[0].toUpperCase() : null; }

// Replace first 64-hex token and the size-like numeric segment in a table row.
function refreshRow(line, newHash, newSize, dateStamp) {
  let out = line.replace(/[0-9A-Fa-f]{64}/, newHash);
  const segs = out.split("|");
  for (let i = 0; i < segs.length; i++) {
    if (/^\s*[\d,]+\s*$/.test(segs[i])) {
      const v = parseInt(segs[i].replace(/,/g, ""), 10);
      if (v > 1000 && v !== newSize) { segs[i] = " " + newSize.toLocaleString("en-US") + " "; break; }
    }
  }
  out = segs.join("|");
  if (newHash && dateStamp) {
    out = out.replace(/\d{4}-\d{2}-\d{2}( \d{2}:\d{2})?/, dateStamp);
  }
  return out;
}

function dateStamp() {
  const d = new Date();
  return d.toISOString().slice(0, 10);
}

function main() {
  console.log("=== BASELINE COHERENCE " + (FIX ? "(--fix)" : "(read-only)") + " ===");
  const bl1 = fs.readFileSync(BL1, "utf8");
  const bl2 = fs.readFileSync(BL2, "utf8");
  const guard = liveGuard();
  if (!guard) div("governance guard suite did not execute cleanly");
  else if (guard.fail !== 0) div(`guard suite has ${guard.fail} FAIL`);
  else ok(`guard suite live: ${guard.pass}/${guard.pass} PASS`);
  const ds = dateStamp();

  // ── P1 §1 / §5 hashes + sizes ──
  const mapped = [...P1_APP, ...P1_PACKS.map(p => ({ row: p.row, file: p.file })), ...P1_CASES, ...P1_GOV];
  let bl1Lines = bl1.split("\n");
  const fixEdits = [];
  for (const m of mapped) {
    const actual = sha(m.file);
    const size = fsize(m.file);
    if (!actual) { div(`missing file for baseline row ${m.row}: ${m.file}`); continue; }
    const r = rowLine(bl1Lines.join("\n"), m.row);
    if (!r) { div(`baseline row not found for ${m.row}`); continue; }
    const declared = firstHex(r.line);
    if (declared !== actual) {
      div(`hash drift ${m.row}: doc ${declared ? declared.slice(0, 8) : "?"} vs actual ${actual.slice(0, 8)}`);
      if (FIX) fixEdits.push({ idx: r.idx, line: refreshRow(r.line, actual, size, ds) });
    } else ok(`hash ${m.row}`);
  }

  // ── P1 §2 per-pack certified + total + footer ──
  let tQ = 0, tC = 0;
  const packCert = {};
  for (const p of P1_PACKS) {
    const s = packStats(p.file);
    if (s.q === null) { div(`cannot read ${p.file}`); continue; }
    if (s.cert + s.arch + s.audit + s.unp + s.ed !== s.q) {
      div(`${p.tag} state-sum mismatch: cert ${s.cert}+arch ${s.arch}+audit ${s.audit}+unp ${s.unp}+ed ${s.ed} != qids ${s.q}`);
    }
    tQ += s.q; tC += s.cert;
    packCert[p.tag] = s.cert;
    const re = new RegExp("\\|\\s*Pack\\s+" + p.tag + "\\s*\\|\\s*([\\d,]+)\\s*\\|\\s*([\\d,]+)\\s*\\|");
    const mm = bl1.match(re);
    if (!mm) div(`§2 row missing for Pack ${p.tag}`);
    else {
      const dQ = parseInt(mm[1].replace(/,/g, ""), 10), dC = parseInt(mm[2].replace(/,/g, ""), 10);
      if (dQ !== s.q || dC !== s.cert) {
        div(`§2 Pack ${p.tag}: doc ${dQ}/${dC} vs raw ${s.q}/${s.cert}`);
        if (FIX) {
          fixEdits.push({ re, pack: p.tag, vals: [s.q, s.cert] });
        }
      } else ok(`§2 Pack ${p.tag} ${s.q}/${s.cert}`);
    }
  }
  const tRe = /\|\s*\*\*Total\*\*\s*\|\s*\*\*([\d,]+)\*\*\s*\|\s*\*\*([\d,]+)\*\*\s*\|/;
  const tm = bl1.match(tRe);
  if (!tm || parseInt(tm[1].replace(/,/g, ""), 10) !== tQ || parseInt(tm[2].replace(/,/g, ""), 10) !== tC) {
    div(`§2 Total mismatch: doc ${tm ? tm[1] + "/" + tm[2] : "?"} vs raw ${tQ}/${tC}`);
    if (FIX) fixEdits.push({ re: tRe, total: true, vals: [tQ, tC] });
  } else ok(`§2 Total ${tQ}/${tC}`);
  const footRe = /^\*Last updated:[^\n]*$/m;
  const footM = bl1.match(footRe);
  const footLine = footM ? footM[0] : "";
  const footCert = (footLine.match(/Certified pool:\s*([\d,]+)/) || [])[1];
  if (!footM || !footCert || parseInt(footCert.replace(/,/g, ""), 10) !== tC) {
    div(`footer Certified mismatch: doc ${footCert || "?"} vs raw ${tC}`);
    if (FIX) fixEdits.push({ footer: true, vals: [tC, tQ] });
  } else ok(`footer Certified ${tC}`);

  // ── P1 §4 rule table + count ──
  const sec4 = bl1.split("## 4. Governance Guard");
  let ruleRows = 0, testLine = null;
  if (sec4.length > 1) {
    const tail = sec4[1].split("## 5.")[0];
    ruleRows = (tail.match(/^\|\s*Rule\s+\d+\s*—/gm) || []).length;
    const tmm = tail.match(/\*\*(\d+)\/(\d+)\s*PASS\*\*/);
    if (tmm) testLine = { a: +tmm[1], b: +tmm[2] };
  }
  if (ruleRows !== 21) {
    div(`§4 rule rows: doc ${ruleRows} vs 21`);
  } else ok("§4 21 rule rows");
  if (guard && (!testLine || testLine.a !== guard.pass || testLine.b !== guard.pass || testLine.a !== testLine.b)) {
    div(`§4 test count: doc ${testLine ? testLine.a + "/" + testLine.b : "?"} vs live ${guard.pass}/${guard.pass}`);
  } else if (guard) ok(`§4 test count ${guard.pass}/${guard.pass}`);

  // ── P2 §1 rows ──
  let p2Q = 0, p2C = 0;
  let bl2Lines = bl2.split("\n");
  const p2Fix = [];
  for (const p of P2_PACKS) {
    const s = packStats(p.file);
    if (s.q === null) { div(`cannot read ${p.file}`); continue; }
    p2Q += s.q; p2C += s.cert;
    const re = new RegExp("\\|\\s*" + p.tag + "\\s*\\|\\s*`?" + escRe(p.row) + "`?\\s*\\|\\s*\\*\\*([\\d,]+)\\*\\*\\s*\\|\\s*([\\d,]+)\\s*\\|\\s*([\\d,]+)\\s*\\|\\s*([\\d,]+)\\s*\\|\\s*([\\d,]+)\\s*\\|\\s*`([0-9a-fA-F]{64})`");
    const mm = bl2.match(re);
    if (!mm) { div(`P2 §1 row missing/unparseable for ${p.tag}`); continue; }
    const actual = sha(p.file);
    const dCur = parseInt(mm[2].replace(/,/g, ""), 10), dCert = parseInt(mm[3].replace(/,/g, ""), 10);
    const dUnp = parseInt(mm[4].replace(/,/g, ""), 10), dArch = parseInt(mm[5].replace(/,/g, ""), 10);
    if (dCur !== s.q || dCert !== s.cert || dUnp !== s.unp || dArch !== s.arch || mm[6].toUpperCase() !== actual) {
      div(`P2 §1 ${p.tag}: doc ${dCur}/${dCert}/${dUnp}/${dArch}/${mm[6].slice(0, 8)} vs raw ${s.q}/${s.cert}/${s.unp}/${s.arch}/${actual.slice(0, 8)}`);
      if (FIX) p2Fix.push({ tag: p.tag, s, hash: actual });
    } else ok(`P2 §1 ${p.tag} ${s.q}/${s.cert}`);
  }

  // Board-authorized prose corrections (P1, 2026-09-13). Applied ONLY via --fix
  // (Rule 7: derived registries regenerate through scripts, never hand-edits).
  // Each pair is raw-verified; a pair that no longer matches is skipped silently
  // (idempotent — already applied).
  const PROSE_FIXES = [
    ["14 items Unprocessed (P1-DC-101..130, Wave 13 tail)",
     "14 items Archived (P1-EC-001..065 DL-012 clones)"],
    ["4 items Unprocessed (P1-DD-076..105, Wave 6 tail)",
     "4 items Archived (P1-ED-001/014/036/046 DL-012 clones)"],
    ["14 Unprocessed P1-DC-101..130)", "14 Archived P1-EC-001..065)"],
    ["4 Unprocessed P1-DD-076..105)", "4 Archived P1-ED-001..046)"],
    ["**S377 IN PROGRESS** — 39 Certified learner-pool items affected",
     "**RESOLVED-in-fact 2026-09-05** — 0 Certified empty-slot items pool-wide (see DEFECT_LIBRARY.md DL-035)"],
    ["| Date | Session | Files Verified | Stable |\n| Date | Session | Files Verified | Stable |",
     "| Date | Session | Files Verified | Stable |"],
  ];

  if (FIX) {
    const ts = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
    // Apply BL1 line edits (hash/size rows)
    let out1 = bl1Lines.join("\n");
    const byIdx = {};
    for (const e of fixEdits.filter(e => e.idx !== undefined)) byIdx[e.idx] = e.line;
    out1 = out1.split("\n").map((l, i) => (byIdx[i] !== undefined ? byIdx[i] : l)).join("\n");
    for (const e of fixEdits.filter(e => e.re && e.pack)) {
      out1 = out1.replace(e.re, (m0) => m0.replace(/([\d,]+)\s*\|\s*([\d,]+)/, `${e.vals[0].toLocaleString("en-US")} | ${e.vals[1].toLocaleString("en-US")}`));
    }
    for (const e of fixEdits.filter(e => e.total)) {
      out1 = out1.replace(e.re, `| **Total** | **${e.vals[0].toLocaleString("en-US")}** | **${e.vals[1].toLocaleString("en-US")}** |`);
    }
    for (const e of fixEdits.filter(e => e.footer)) {
      const brk = ["A", "B", "C", "D", "E"].map(t => `${t} ${packCert[t].toLocaleString("en-US")}`).join(" + ");
      const nonCert = tQ - tC;
      out1 = out1.replace(footRe, `*Last updated: ${ds} baseline_coherence --fix — Certified pool: ${e.vals[0].toLocaleString("en-US")} (${brk}); ${nonCert} non-Certified (Archived DL-012). QID: ${e.vals[1].toLocaleString("en-US")}. Governance guard ${guard.pass}/${guard.pass}.*`);
    }
    // §4 regeneration (full 19-rule table + live count)
    const ruleBody = RULES.map(([n, s]) => `| Rule ${n} — ${s} | BLOCK | Active |`).join("\n");
    const sec4Re = /## 4\. Governance Guard[\s\S]*?\| \*\*Test Suite\*\* \| \*\*[\d/]+\s*PASS\*\* \|[^\n]*/;
    const newSec4 = `## 4. Governance Guard\n\n| Rule | Level | Status |\n|------|-------|--------|\n${ruleBody}\n| **Test Suite** | **${guard.pass}/${guard.pass} PASS** | **Verified ${ds} (baseline_coherence --fix)** |`;
    out1 = out1.replace(sec4Re, newSec4);
    let proseApplied = 0;
    for (const [oldS, newS] of PROSE_FIXES) {
      if (out1.includes(oldS)) { out1 = out1.replace(oldS, newS); proseApplied++; }
    }
    // §6: merge fragmented mini-tables — keep the first Date/Session header+
    // separator, drop repeats. Data rows untouched.
    let seen6 = 0;
    const before6 = out1;
    out1 = out1.replace(/\| Date \| Session \| Files Verified \| Stable \|\n\|------\|---------\|---------------\|--------\|\n/g,
      (m) => (++seen6 === 1 ? m : ""));
    if (out1 !== before6) proseApplied++;
    fs.copyFileSync(BL1, BL1 + `.bak-coherence-${ts}`);
    fs.writeFileSync(BL1, out1, "utf8");
    console.log(`  FIX: ${BL1} rewritten (backup .bak-coherence-${ts}); prose corrections applied: ${proseApplied}/${PROSE_FIXES.length}`);

    // P2 §1 numeric + hash refresh
    let out2 = bl2Lines.join("\n");
    for (const f of p2Fix) {
      const rowp = P2_PACKS.find(p => p.tag === f.tag).row;
      const re = new RegExp("(\\|\\s*" + f.tag + "\\s*\\|\\s*`?" + escRe(rowp) + "`?\\s*\\|\\s*\\*\\*[\\d,]+\\*\\*\\s*\\|\\s*)[\\d,]+(\\s*\\|\\s*)[\\d,]+(\\s*\\|\\s*)[\\d,]+(\\s*\\|\\s*)[\\d,]+(\\s*\\|\\s*`)[0-9a-fA-F]{64}(`)");
      out2 = out2.replace(re, `$1${f.s.q.toLocaleString("en-US")}$2${f.s.cert.toLocaleString("en-US")}$3${f.s.unp.toLocaleString("en-US")}$4${f.s.arch.toLocaleString("en-US")}$5${f.hash.toLowerCase()}$6`);
    }
    // P2 header summary refresh
    out2 = out2.replace(/Pool now \*\*[\d,]+\/[\d,]+ Certified[^\n]*/, `Pool now **${p2C.toLocaleString("en-US")}/${p2Q.toLocaleString("en-US")} Certified** (${ds} coherence refresh)`);
    out2 = out2.replace(/3,450\/3,450 Certified \(0 Unprocessed, 0 Archived\)/, `${p2C.toLocaleString("en-US")}/${p2Q.toLocaleString("en-US")} Certified`);
    fs.copyFileSync(BL2, BL2 + `.bak-coherence-${ts}`);
    fs.writeFileSync(BL2, out2, "utf8");
    console.log(`  FIX: ${BL2} rewritten (backup .bak-coherence-${ts})`);
    console.log("  NOTE: prose corrections (§2 notes, §3 DL-035, P2 header claim) remain manual.");
  }

  console.log(`\nDIVERGENCES: ${divergences.length}`);
  if (divergences.length) { console.log("*** BASELINE INCOHERENT ***"); process.exit(1); }
  console.log("*** BASELINE COHERENT ***");
}
main();
