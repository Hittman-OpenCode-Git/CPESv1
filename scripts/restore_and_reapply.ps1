function Get-Object($content, $qid) {
    $idx = $content.IndexOf('"QuestionID": "' + $qid + '"')
    if ($idx -lt 0) { return @($null, -1, -1) }
    $brace = 0; $start = $idx
    while ($start -ge 0) {
        if ($content[$start] -eq '}') { $brace++ }
        elseif ($content[$start] -eq '{') { $brace--; if ($brace -eq 0) { break } }
        $start--
    }
    $end = $idx; $brace = 0
    while ($end -lt $content.Length) {
        if ($content[$end] -eq '{') { $brace++ }
        elseif ($content[$end] -eq '}') { $brace--; if ($brace -eq 0) { $end++; break } }
        $end++
    }
    return @($content.Substring($start, $end - $start), $start, $end)
}

function Replace-In-Object($content, $objStart, $objEnd, $field, $newValue) {
    $obj = $content.Substring($objStart, $objEnd - $objStart)
    $pattern = '("' + $field + '"\s*:\s*")((?:[^"\\]|\\.)*)(")'
    $newObj = $obj -replace $pattern, ('$1' + $newValue + '$3')
    if ($newObj -ne $obj) {
        return $content.Substring(0, $objStart) + $newObj + $content.Substring($objEnd)
    }
    return $content
}

